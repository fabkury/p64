#!/usr/bin/env python3
r"""Bakes the two layers of the p64 logo into the firmware for the intro animations (p101).

    python tools\gen_logo_assets.py        (from firmware/; needs Pillow)

Reads docs/images/logo/v2/p64-logo-v2-L0.png (the panel with the bird) and -L1.png (the
wordmark, drawn on top), both 64x64 RGBA on the panel's canvas, trims the transparent
border of each and writes components/p64_intro/src/logo_assets.hpp and .cpp: one RGBA
array per layer plus the trimmed box's position on the canvas, so a layer drawn at its
home offset lands exactly where the untrimmed image would. Rerun after editing a PNG; the
output is committed, so the build needs neither Pillow nor the PNGs (ADR 0008).

It also writes the flat logo for the documentation and the web flasher (p111): the two
layers composited into docs/images/logo/v2/p64-logo-v2.png (64x64, as the panel shows it)
and a 2x nearest-neighbour copy, p64-logo-v2-2x.png (128x128), the one the README,
docs/README.md and docs/web-flasher use. Both are committed too.
"""

import os
import sys

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
FIRMWARE = os.path.abspath(os.path.join(HERE, ".."))
LOGO_DIR = os.path.join(FIRMWARE, "..", "docs", "images", "logo", "v2")
OUT_DIR = os.path.join(FIRMWARE, "components", "p64_intro", "src")
LAYERS = [("L0", "kLayer0", "the panel with the bird"), ("L1", "kLayer1", "the wordmark, drawn on top")]
FLAT = os.path.join(LOGO_DIR, "p64-logo-v2.png")
FLAT_2X = os.path.join(LOGO_DIR, "p64-logo-v2-2x.png")


def write_flat(layers):
    """Composites the layers in order and saves the 64x64 logo and its 2x nearest-neighbour copy."""
    flat = Image.new("RGBA", (64, 64), (0, 0, 0, 0))
    for img in layers:
        flat = Image.alpha_composite(flat, img)
    flat.save(FLAT, optimize=True)
    flat.resize((128, 128), Image.NEAREST).save(FLAT_2X, optimize=True)


def main():
    hpp = ["// Generated by tools/gen_logo_assets.py from docs/images/logo/v2; do not edit.",
           "// The p64 logo as the two layers the intro animations move separately (p101): layer 0",
           "// is the panel with the bird, layer 1 the wordmark drawn on top. Each is trimmed to its",
           "// opaque box and keeps the box's position on the 64x64 canvas, so drawing it at (x, y)",
           "// puts every pixel where the untrimmed image had it.",
           "#pragma once", "", "#include <cstdint>", "", "namespace p64::intro::logo {", "",
           "struct Layer {", "  int16_t x, y;  // home position of the trimmed box on the canvas",
           "  int16_t w, h;", "  const uint8_t *rgba;  // w*h*4 bytes, row-major; alpha is 0 or 255", "};", ""]
    cpp = ["// Generated by tools/gen_logo_assets.py from docs/images/logo/v2; do not edit.",
           "#include \"logo_assets.hpp\"", "", "namespace p64::intro::logo {", "namespace {"]
    layers = []
    for suffix, sym, what in LAYERS:
        path = os.path.join(LOGO_DIR, f"p64-logo-v2-{suffix}.png")
        img = Image.open(path).convert("RGBA")
        if img.size != (64, 64):
            sys.exit(f"{path}: expected 64x64, got {img.size}")
        layers.append(img)
        alpha = img.split()[3].point(lambda a: 255 if a >= 128 else 0)
        box = alpha.getbbox()
        if not box:
            sys.exit(f"{path}: fully transparent")
        x0, y0, x1, y1 = box
        crop = img.crop(box)
        data = []
        for r, g, b, a in crop.getdata():
            if a < 128:
                data += [0, 0, 0, 0]
            else:
                data += [r, g, b, 255]
        cpp.append(f"const uint8_t {sym}_rgba[] = {{")
        for i in range(0, len(data), 24):
            cpp.append("  " + ", ".join(str(v) for v in data[i:i + 24]) + ",")
        cpp.append("};")
        hpp.append(f"extern const Layer {sym};  // {what}: {crop.width}x{crop.height} at ({x0}, {y0}), {len(data)} bytes")
        cpp.append(f"__LAYER__{sym}|{x0}|{y0}|{crop.width}|{crop.height}")
    hpp += ["", "}  // namespace p64::intro::logo", ""]
    defs = [line for line in cpp if line.startswith("__LAYER__")]
    cpp = [line for line in cpp if not line.startswith("__LAYER__")]
    cpp.append("}  // namespace")
    cpp.append("")
    for d in defs:
        sym, x0, y0, w, h = d[len("__LAYER__"):].split("|")
        cpp.append(f"const Layer {sym}{{{x0}, {y0}, {w}, {h}, {sym}_rgba}};")
    cpp += ["", "}  // namespace p64::intro::logo", ""]
    with open(os.path.join(OUT_DIR, "logo_assets.hpp"), "w", newline="\n") as f:
        f.write("\n".join(hpp))
    with open(os.path.join(OUT_DIR, "logo_assets.cpp"), "w", newline="\n") as f:
        f.write("\n".join(cpp))
    write_flat(layers)
    print("wrote", OUT_DIR, FLAT, "and", FLAT_2X, "from", LOGO_DIR)


if __name__ == "__main__":
    main()
